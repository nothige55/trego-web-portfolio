type DemoActivityInput = {
  readonly name: string;
  readonly pathId: string;
  readonly parentPathId: string;
  readonly position: number;
  readonly placeId: number;
  readonly latitude: number;
  readonly longitude: number;
  readonly startTime: string | null;
  readonly memo?: string | null;
  readonly markerType?: string | null;
  readonly travelMode?: string | null;
  readonly travelTime?: number | null;
  readonly travelDistance?: number | null;
};

// 장소마다 반복되는 nullable API 필드를 기본값으로 채워 일정 자체를 읽기 쉽게 유지한다.
function createActivity({
  name,
  pathId,
  parentPathId,
  position,
  placeId,
  latitude,
  longitude,
  startTime,
  memo = null,
  markerType = "default",
  travelMode = null,
  travelTime = null,
  travelDistance = null,
}: DemoActivityInput): PlannerActivityNode {
  return {
    id: `demo-${pathId}`,
    kind: "activity",
    name,
    pathId,
    parentPathId,
    position,
    activityType: "place",
    memo,
    markerType,
    travelMode,
    travelTime,
    travelDistance,
    travelCost: null,
    startTime,
    endTime: null,
    placeId,
    latitude,
    longitude,
    googlePlaceId: `demo-${pathId}`,
  };
}

